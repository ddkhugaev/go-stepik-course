package main

import "fmt"

// глобальная переменная уровня пакета
var number1, number2 = 10, 20

func main() {
	// Статическая типизация, приведение типов и оператор короткого объявления

	// строгая статическая типизация
	// если пременная объявлена с типом int
	// в нее может быть записано только значение int

	// в go нет автоматического приведения типов
	// нельзя смешивать int и float64

	// явное приведение типов
	// тип(значение)
	// примеры
	// int -> float64
	// float64 -> int (потеря дробной части (она именно отрбасывается))

	// автоматический вывод типов (type inference)
	// go умеет автоматически определять тип значения
	var inferredInt = 8
	var inferredFloat = 16.32
	var inferredString = "hello"
	var inferredBool = true
	fmt.Println(inferredInt, inferredFloat, inferredString, inferredBool)
	// правило вывода типов
	// целое число без точки -> int
	// число с точкой -> float64
	// строка в "" -> string
	// true/false -> bool

	// оператор короткого объявления :=
	// имя := значение
	// эквивалентно
	// var имя тип = значение
	// этот оператор работает только внутри функции
	// на уровне пакета обязательно использовать полную форму объявления

	// множественное объявление переменных
	x, y := 2, 4
	fmt.Println(x, y)

	var a, b = 8, 16
	fmt.Println(a, b)

	var c, d int = 32, 64
	fmt.Println(c, d)

	var (
		e     = 128
		f int = 256
		g     = 512
	)
	fmt.Println(e, f, g)

	// := может использоватьс я при множественном присваивании, если хотя бы одна переменная слева новая
	x, z := 12, 13
	fmt.Println(x, z)

	// go проверяет типы во время компиляции, а не во время выполнения

	// shadowing (затенение) переменных в go
	// если локальная переменная объявляется с тем же именем, что и глобальная
	// то глобальная затеняется и мы используемм локальную
	// при это глобальная никак не меняется
	fmt.Println(number1, number2)
	number1, number2 := 30, 40
	fmt.Println(number1, number2)

	// каждая пара вигурных скобок {} создает новую область видимости
	// переменные из внешней области доступны во внутренней, пока не затенены
	// после выхода из области затеняющая переменная исчезает, внешняя остается неизменной
}
