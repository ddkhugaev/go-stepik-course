package main

import (
	"fmt"
	"unsafe"
)

func main() {
	// создание переменной
	var age int = 35

	// значение переменной
	fmt.Println(age)
	fmt.Printf("%v\n", age)

	// тип переменной
	fmt.Printf("%T\n", age)

	// адрес в памяти
	// оператор & возвращает адрес переменной
	// %p выводит его в шестнадцатеричном формате (префикс 0x)
	fmt.Printf("%p\n", &age)

	// изменение значения не меняет адрес переменной
	age = 40
	fmt.Printf("%p\n", &age)

	// размер переменной
	fmt.Println(unsafe.Sizeof(age))

	// сама переменная строки занимает 16 байт
	// среди них не значение, а метаданные (указатель и длина пополам)
	var stringVar string = ""
	fmt.Println(unsafe.Sizeof(stringVar))

	// адрес переменной строки (дескриптора) определяется так же
	fmt.Printf("%p\n", &stringVar)

	// адрес реального массива байт определяется по-другому
	fmt.Println(unsafe.StringData(stringVar))

	// при изменении значения строки меняется сслыка на значение
	stringVar = "hello"
	fmt.Println(unsafe.StringData(stringVar))

	// при этом адрес дескриптора (структуры) не меняется
	fmt.Println(&stringVar)

	// минимальный тип для числа
	// 0-255 -> uint8 (1 байт)
	// 0-65535 -> uint16 (2 байта)
	// -128 до 127 -> int8 (1 байт)
	// -32768 до 32767 -> int16 (2 байта)
	// go проверяет константы на этапе компиляции
	// так что не получится записать слишком большое значение

	// почему адрес переменной меняется при каждом запуске?
	// aslr (address space layout randomization)
	// механизм безопасности ос
	// рандомизирует адреса памяти при каждом запуске программы
	// для защиты от определенных типов атак
}
