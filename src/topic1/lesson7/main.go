package main

import "fmt"

func main() {
	// Правила именования идентификаторов

	// go чувствителен к регистру
	// это разные переменные
	var value int = 1
	var Value int = 2
	fmt.Println(value, Value)

	// первая буква имени определяет видимость
	// заглавная буква -> экспортируемая (public)
	// строчная буква -> неэкспортируемая (private)

	// разрешено
	// использовать буквы unicode (оба регистра)
	// использовать нижнее подчеркивание
	// использовать цифры, но не на первой позиции
	// не рекомендуется использовать не латинские символы

	// лучшие практики наименования
	// использование осмысленных слов
	// camelCase для составных имен
	// длинные названия - это нормально
	// короткие имена только для локальных переменных (циклы)
	// контекст важнее длины
}
