package main

import "fmt"

func main() {
	// Арифметические операции

	// стандартный набор арифметических операций
	a := 14
	b := 5
	fmt.Println(a+b, a-b, a*b, a/b, a%b)

	// если при делении оба операнда целые, то результат тоже будет целым (неполное частное)
	// дробная часть отбрасывается

	// оператор % работает только с целыми числами
	// для вещественных чисел используется math.Mod()

	// в go нет автоматического приведения типов
	// чтобы выполнить арифеметическую операцию с разными типами
	// надо явно привести один из операндов к виду другого (type casting)
	// при приведении float к int дробная часть отбрасывается
	x := 3.9
	y := -3.9
	fmt.Println(int(x), int(y))

	// тип результата арифметической операции всегда совпадает с типом операндов
}
