package main

import "fmt"

func main() {
	// Инкремент, декремент и составные операторы: критические отличия Go

	// инкремент и декремент есть только в постфиксной форме
	// это операторы (statement), а не выражения (expression)
	// они не возвращают значения

	// составные операторы присваивания
	value := 10
	value += 10
	value -= 5
	value *= 3
	value /= 5
	value %= 2
	fmt.Println(value)

	// стандартные побитовые операции для работы с двоичнми числами
	a := 5
	b := 3
	// побитовое и (and)
	fmt.Println(a & b)
	// побитовое или (or)
	fmt.Println(a | b)
	// побитовое исключающее или (xor)
	fmt.Println(a ^ b)
	// сдвиг влево (умножение на два)
	fmt.Println(a << 1)
	// сдвиг вправо (деление на два)
	fmt.Println(a >> 1)
	
	// составные побитовые операторы
	// 	x &= y
	// x |= y
	// x ^= y
	// x <<= 2
	// x >>= 2
}
